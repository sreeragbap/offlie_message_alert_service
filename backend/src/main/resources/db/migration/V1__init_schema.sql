-- Offline Message Alert Service: initial schema.
-- All tables live in the private "app" schema, which Supabase's Data API does not expose.
-- The mobile app never talks to these tables directly; only the Spring Boot backend does.

create schema if not exists app;

-- One row per Supabase Auth user (id = JWT "sub"). Credentials live in Supabase Auth, never here.
create table app.user_account (
    id           uuid primary key,
    display_name text check (char_length(display_name) between 1 and 80),
    phone_e164   text check (phone_e164 ~ '^\+[1-9][0-9]{6,14}$'),
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now()
);

create table app.alert_preference (
    user_id                          uuid primary key references app.user_account (id) on delete cascade,
    default_delay_minutes            integer not null default 30 check (default_delay_minutes between 0 and 1440),
    max_alerts_per_recipient_per_day integer not null default 3 check (max_alerts_per_recipient_per_day between 1 and 10),
    max_alerts_per_day               integer not null default 20 check (max_alerts_per_day between 1 and 50),
    message_template                 text not null check (char_length(message_template) between 10 and 300),
    updated_at                       timestamptz not null default now()
);

create table app.recipient (
    id             uuid primary key default gen_random_uuid(),
    user_id        uuid not null references app.user_account (id) on delete cascade,
    display_name   text not null check (char_length(display_name) between 1 and 80),
    phone_e164     text not null check (phone_e164 ~ '^\+[1-9][0-9]{6,14}$'),
    alerts_enabled boolean not null default true,
    -- The recipient asked not to receive alerts. Blocks alerts regardless of alerts_enabled.
    opted_out      boolean not null default false,
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now(),
    unique (user_id, phone_e164)
);

create index recipient_user_idx on app.recipient (user_id);

-- An alert is a request to tell a recipient that a message may be waiting for them.
-- It never stores the content of the original message.
create table app.alert (
    id                  uuid primary key default gen_random_uuid(),
    user_id             uuid not null references app.user_account (id) on delete cascade,
    -- Kept for history when a recipient is removed.
    recipient_id        uuid references app.recipient (id) on delete set null,
    -- Generated by the client per user action; makes retried POSTs idempotent.
    client_request_id   uuid not null,
    trigger_source      text not null check (trigger_source in ('USER_TRIGGERED', 'DELIVERY_TIMEOUT')),
    platform            text not null check (platform in ('WHATSAPP', 'TELEGRAM', 'MESSENGER', 'INSTAGRAM', 'SIGNAL', 'SMS', 'OTHER')),
    channel             text not null check (channel in ('DEVICE_SMS', 'SERVER_SMS')),
    state               text not null check (state in (
                            'SCHEDULED', 'DUE', 'SENT_FROM_DEVICE',
                            'SENDING', 'SMS_ACCEPTED', 'SMS_DELIVERED', 'SMS_FAILED', 'SMS_UNKNOWN',
                            'CANCELLED', 'SKIPPED', 'EXPIRED')),
    message_text        text not null check (char_length(message_text) between 1 and 320),
    due_at              timestamptz not null,
    attempts            integer not null default 0,
    locked_until        timestamptz,
    provider            text,
    provider_message_id text,
    last_error          text,
    created_at          timestamptz not null default now(),
    updated_at          timestamptz not null default now(),
    completed_at        timestamptz,
    unique (user_id, client_request_id)
);

create index alert_scheduled_due_idx on app.alert (due_at) where state = 'SCHEDULED';
create index alert_due_state_idx on app.alert (due_at) where state = 'DUE';
create index alert_sending_lock_idx on app.alert (locked_until) where state = 'SENDING';
create index alert_user_created_idx on app.alert (user_id, created_at desc);
create index alert_recipient_created_idx on app.alert (recipient_id, created_at);
create unique index alert_provider_message_uq on app.alert (provider, provider_message_id)
    where provider_message_id is not null;

-- Defence in depth: Supabase's client-facing roles get nothing in this schema.
do $$
begin
    if exists (select 1 from pg_roles where rolname = 'anon') then
        execute 'revoke all on schema app from anon';
        execute 'revoke all on all tables in schema app from anon';
    end if;
    if exists (select 1 from pg_roles where rolname = 'authenticated') then
        execute 'revoke all on schema app from authenticated';
        execute 'revoke all on all tables in schema app from authenticated';
    end if;
end
$$;
