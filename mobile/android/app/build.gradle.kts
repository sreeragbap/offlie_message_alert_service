// Release builds may use http:// only for localhost (adb reverse) and, when API_BASE_URL in the
// --dart-define-from-file config is http://, its host (e.g. this Mac's Wi-Fi IP for testing).
val cleartextHosts = (findProperty("dart-defines") as String?).orEmpty()
    .split(",").filter { it.isNotEmpty() }
    .map { String(Base64.getDecoder().decode(it)) }
    .firstOrNull { it.startsWith("API_BASE_URL=http://") }
    ?.let { listOf(URI(it.removePrefix("API_BASE_URL=")).host) }
    .orEmpty()
val networkConfigDir = layout.buildDirectory.dir("generated/networkSecurity").get().asFile
networkConfigDir.resolve("xml/network_security_config.xml").apply {
    parentFile.mkdirs()
    val domains = (listOf("localhost", "127.0.0.1") + cleartextHosts).distinct()
        .joinToString("\n") { "        <domain includeSubdomains=\"false\">$it</domain>" }
    writeText(
        """
        |<?xml version="1.0" encoding="utf-8"?>
        |<!-- Generated by app/build.gradle.kts. -->
        |<network-security-config>
        |    <domain-config cleartextTrafficPermitted="true">
        |$domains
        |    </domain-config>
        |</network-security-config>
        |""".trimMargin(),
    )
}

